#!/usr/bin/env python3
"""Write the Thunar/GTK stylesheet for the active Caelestia style.

The stylesheet itself uses the GTK named colours from ``gtk.css`` so the
palette keeps following the scheme. This script only picks the Material or
Fluent layout variant and installs it for GTK 3 and GTK 4.
"""

from __future__ import annotations

import json
import os
import shutil
import sys
import time
from pathlib import Path

STYLES = {
    "material": "thunar-material.css",
    "fluent": "thunar-fluent.css",
}
MARKER = "Generated by Caelestia"


def read_style() -> str:
    if len(sys.argv) > 1 and sys.argv[1] in STYLES:
        return sys.argv[1]

    state_dir = Path(os.environ.get("XDG_STATE_HOME", Path.home() / ".local/state"))
    try:
        data = json.loads((state_dir / "caelestia" / "theme.json").read_text())
        current = data.get("current")
        if current in STYLES:
            return current
    except (OSError, ValueError):
        pass

    return "fluent"


def main() -> int:
    style = read_style()
    source = Path(__file__).resolve().parent / STYLES[style]
    if not source.is_file():
        print(f"Missing Thunar style template: {source}", file=sys.stderr)
        return 1

    content = source.read_text()
    config_dir = Path(os.environ.get("XDG_CONFIG_HOME", Path.home() / ".config"))

    for version in ("gtk-3.0", "gtk-4.0"):
        gtk_dir = config_dir / version
        gtk_dir.mkdir(parents=True, exist_ok=True)
        target = gtk_dir / "thunar.css"

        if target.is_file():
            try:
                existing = target.read_text()
            except OSError:
                existing = ""
            if MARKER not in existing:
                backup = target.with_name(f"thunar.css.bak-{time.strftime('%Y%m%d-%H%M%S')}")
                shutil.copy2(target, backup)

        target.write_text(content)

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
